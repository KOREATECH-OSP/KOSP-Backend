-- ============================================
-- Resume ↔ Material Auto-Link (과제/EL 자료 → 이력서 프로젝트 자동 연결)
-- 설계:
--  · 이력서(user_resume)는 resume_data(JSONB) 스냅샷이라 원본 변경이 전파되지 않는다.
--  · 자동 프로젝트는 material_item 에서 "실시간 투영"으로 계산한다
--    (auto_imported=true 인 자료 = 자동 프로젝트 후보). 원본이 바뀌면 자동 반영된다.
--  · 이 테이블은 그 투영에 대한 "예외"만 저장한다:
--      - deleted_by_user=true  → 사용자가 삭제한 자동 프로젝트(재삽입 금지, tombstone)
--      - user_edited=true       → 사용자가 수정 → overrides(JSONB)로 원본 위에 덮어씀(동기화 보호)
--      - visibility             → 프로젝트 단위 공개 override (기본 비공개)
--  · 예외가 없는 자료는 자동으로 이력서에 포함된다.
-- ============================================

CREATE TABLE resume_material_project
(
    id               BIGINT      GENERATED BY DEFAULT AS IDENTITY,
    created_at       TIMESTAMP   NOT NULL,
    updated_at       TIMESTAMP   NOT NULL,
    resume_id        BIGINT      NOT NULL,
    material_item_id BIGINT      NOT NULL,
    source_type      VARCHAR(30) NOT NULL,                    -- AUNURI_ASSIGNMENT / AUNURI_EL
    user_edited      BOOLEAN     NOT NULL DEFAULT FALSE,      -- 사용자 수정본 보호 플래그
    deleted_by_user  BOOLEAN     NOT NULL DEFAULT FALSE,      -- 삭제 tombstone(재삽입 금지)
    overrides        JSONB,                                   -- 사용자가 수정한 필드만 저장
    visibility       VARCHAR(10) NOT NULL DEFAULT 'PRIVATE',  -- 프로젝트 단위 공개 override
    last_synced_at   TIMESTAMP,
    CONSTRAINT pk_resume_material_project PRIMARY KEY (id),
    CONSTRAINT uq_resume_material UNIQUE (resume_id, material_item_id),
    CONSTRAINT fk_rmp_resume FOREIGN KEY (resume_id) REFERENCES user_resume (id) ON DELETE CASCADE,
    CONSTRAINT fk_rmp_material FOREIGN KEY (material_item_id) REFERENCES material_item (id) ON DELETE CASCADE
);

CREATE INDEX idx_rmp_resume ON resume_material_project (resume_id);
CREATE INDEX idx_rmp_material ON resume_material_project (material_item_id);
