-- GitHub Organization 등록 기능 — 조직 멤버 테이블
-- role: OWNER / MEMBER
-- status: LINKED(K-OSP 가입 완료) / NOT_JOINED(미가입) / REMOVED(조직에서 제거됨)
-- user_id: K-OSP 미가입자는 NULL
CREATE TABLE organization_members
(
    id              BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    created_at      TIMESTAMP    NOT NULL,
    updated_at      TIMESTAMP    NOT NULL,
    organization_id BIGINT       NOT NULL,
    user_id         BIGINT,
    github_user_id  BIGINT       NOT NULL,
    github_username VARCHAR(255) NOT NULL,
    role            VARCHAR(20)  NOT NULL,
    status          VARCHAR(20)  NOT NULL DEFAULT 'NOT_JOINED',
    joined_at       TIMESTAMP,
    synced_at       TIMESTAMP    NOT NULL,
    CONSTRAINT pk_organization_members PRIMARY KEY (id),
    CONSTRAINT uc_organization_members_org_github UNIQUE (organization_id, github_user_id),
    CONSTRAINT fk_organization_members_on_org FOREIGN KEY (organization_id) REFERENCES organizations (id),
    CONSTRAINT fk_organization_members_on_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE INDEX idx_organization_members_github_user_id ON organization_members (github_user_id);
