-- ============================================
-- Resume System
-- 사용자 1:1 이력서 데이터 저장
-- ============================================

CREATE TABLE user_resume
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id     BIGINT       NOT NULL,
    created_at  TIMESTAMP    NOT NULL,
    updated_at  TIMESTAMP    NOT NULL,
    resume_data JSONB        NOT NULL DEFAULT '{}',
    CONSTRAINT pk_user_resume PRIMARY KEY (id),
    CONSTRAINT uc_user_resume_user UNIQUE (user_id),
    CONSTRAINT fk_user_resume_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE INDEX idx_user_resume_user_id ON user_resume (user_id);
