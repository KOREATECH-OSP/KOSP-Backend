-- GitHub Organization 등록 기능 — 조직 기본 정보 테이블
-- status: ACTIVE / PENDING / DISCONNECTED
CREATE TABLE organizations
(
    id                    BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    created_at            TIMESTAMP    NOT NULL,
    updated_at            TIMESTAMP    NOT NULL,
    github_org_id         BIGINT       NOT NULL,
    github_org_name       VARCHAR(255) NOT NULL,
    display_name          VARCHAR(255),
    avatar_url            VARCHAR(500),
    registered_by_user_id BIGINT       NOT NULL,
    status                VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    CONSTRAINT pk_organizations PRIMARY KEY (id),
    CONSTRAINT uc_organizations_github_org_id UNIQUE (github_org_id),
    CONSTRAINT fk_organizations_on_user FOREIGN KEY (registered_by_user_id) REFERENCES users (id)
);
